import android.content.Context
import android.graphics.Typeface
import androidx.compose.material3.Typography
import androidx.compose.ui.text.TextStyle
import androidx.compose.ui.text.font.FontFamily
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.sp

object AppFonts {
    @Volatile
    private var cachedWenKai: FontFamily? = null

    fun wenKai(context: Context): FontFamily {
        cachedWenKai?.let { return it }
        return synchronized(this) {
            cachedWenKai ?: run {
                val tf = Typeface.createFromAsset(context.assets, "LXGWWenKai-Regular.ttf")
                FontFamily(tf).also { cachedWenKai = it }
            }
        }
    }
}

